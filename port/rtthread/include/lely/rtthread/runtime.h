typedef struct lely_rtt_runtime lely_rtt_runtime_t;

/** @brief Static CANopen device description generated by Lely dcf2c. */
struct co_sdev;

/** @brief Returned by NMT snapshot APIs before the requested state is ready. */
#define LELY_RTT_NMT_STATE_UNAVAILABLE 0xffu

