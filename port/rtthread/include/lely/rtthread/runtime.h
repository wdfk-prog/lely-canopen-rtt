rt_err_t lely_rtt_sdo_request_get_id(const lely_rtt_sdo_request_t *request,
        rt_uint32_t *request_id);

/**
 * @brief Wait for one request completion event.
 *
 * A request is intended to have one waiting caller at a time. timeout_ms
 * accepts RT_WAITING_FOREVER, 0 for a non-blocking poll, or a
 * positive millisecond timeout. Protocol timeout is configured separately by
 * the post function and is reported as an SDO abort code. A wait timeout does
 * not cancel the SDO transaction; the caller may wait again.
 *
 * @param request Posted request object.
 * @param timeout_ms Wait timeout in milliseconds, RT_WAITING_FOREVER, or 0.
 * @return RT_EOK on terminal completion, an RT-Thread wait error/timeout, or
 *         -RT_EINVAL for an invalid request/timeout.
 */
rt_err_t lely_rtt_sdo_request_wait(lely_rtt_sdo_request_t *request,
        rt_int32_t timeout_ms);

/**
 * @brief Read the terminal result after completion.
 * @param request Completed request object.
 * @param result Output immutable result view.
 * @return RT_EOK on success, -RT_EBUSY before completion, or -RT_EINVAL.
 */
rt_err_t lely_rtt_sdo_request_get_result(
        const lely_rtt_sdo_request_t *request,
        struct lely_rtt_sdo_result *result);

/**
 * @brief Queue an SDO upload (remote object read).
 *
 * The owner lazily creates an application-owned Client-SDO using the CiA 301
 * predefined connection for node_id. It never borrows the NMT boot CSDO. This
 * first implementation therefore does not select custom 0x1280 Client-SDO
 * communication parameters. One application request is active per remote node,
 * and the application receiver is stopped again after completion so it cannot
 * consume NMT boot/configuration responses while idle. Requests are rejected
 * while NMT boot or a pending stop/reset transition owns the node. timeout_ms
 * must be in the range 1..INT_MAX milliseconds.
 *
 * @param runtime Started runtime with a configured local NMT Master.
 * @param request Fresh single-use request object.
 * @param node_id Remote Node-ID in the range 1..127; the local Master Node-ID
 *                is rejected.
 * @param index Remote object dictionary index.
 * @param subindex Remote object dictionary sub-index.
 * @param timeout_ms CSDO protocol timeout in milliseconds; 1..INT_MAX.
 * @return RT_EOK when queued; otherwise an argument, admission, allocation, or
 *         RT message-queue error. Remote SDO failures are reported in result.
 */
rt_err_t lely_rtt_runtime_post_sdo_upload(lely_rtt_runtime_t *runtime,
        lely_rtt_sdo_request_t *request, rt_uint8_t node_id,
        rt_uint16_t index, rt_uint8_t subindex, rt_uint32_t timeout_ms);

/**
 * @brief Queue an SDO download (remote object write).
 *
 * The input bytes are copied before this function returns, so the caller does
 * not need to retain data after a successful post.
 *
 * @param runtime Started runtime with a configured local NMT Master.
 * @param request Fresh single-use request object.
 * @param node_id Remote Node-ID in the range 1..127; the local Master Node-ID
 *                is rejected.
 * @param index Remote object dictionary index.
 * @param subindex Remote object dictionary sub-index.
 * @param data Bytes to download; copied by the post call.
 * @param size Number of bytes in data; must be non-zero.
 * @param timeout_ms CSDO protocol timeout in milliseconds; 1..INT_MAX.
 * @return RT_EOK when queued; otherwise an argument, admission, allocation, or
 *         RT message-queue error. Remote SDO failures are reported in result.
 */
rt_err_t lely_rtt_runtime_post_sdo_download(lely_rtt_runtime_t *runtime,
        lely_rtt_sdo_request_t *request, rt_uint8_t node_id,
        rt_uint16_t index, rt_uint8_t subindex, const void *data,
        rt_size_t size, rt_uint32_t timeout_ms);
#endif /* defined(PKG_LELY_USING_MASTER_SDO) */

